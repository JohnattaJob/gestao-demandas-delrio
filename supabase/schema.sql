create policy areas_read_authenticated on public.areas
  for select to authenticated using (active = true);

create policy profiles_read_self_or_manager on public.profiles
  for select to authenticated using (id = (select auth.uid()) or public.is_manager());
-- Não há políticas de INSERT/UPDATE/DELETE para profiles: usuários não podem
-- promover a própria função nem alterar seu vínculo de área pelo cliente.

create policy requests_read_authorized on public.requests
  for select to authenticated using (public.can_access_request(id));
create policy requests_create_self on public.requests
  for insert to authenticated
  with check (
    requester_id = (select auth.uid())
    and exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.active = true)
  );
create policy requests_update_authorized on public.requests
  for update to authenticated
  using (public.is_manager() or owner_id = (select auth.uid()) or exists (
    select 1 from public.request_assignees ra
    where ra.request_id = id and ra.profile_id = (select auth.uid())
  ))
  with check (public.can_access_request(id));
create policy requests_delete_manager on public.requests
  for delete to authenticated using (public.is_manager());

create policy assignees_read_authorized on public.request_assignees
  for select to authenticated using (public.can_access_request(request_id));
create policy assignees_manage_manager on public.request_assignees
  for all to authenticated using (public.is_manager()) with check (public.is_manager());

create policy history_read_authorized on public.request_history
  for select to authenticated using (public.can_access_request(request_id));
create policy history_insert_authorized on public.request_history
  for insert to authenticated
  with check (changed_by = (select auth.uid()) and public.can_access_request(request_id));

create policy materials_read_authenticated on public.materials
  for select to authenticated using (true);
create policy materials_insert_stock_managers on public.materials
  for insert to authenticated with check (public.can_manage_stock());
create policy materials_update_stock_managers on public.materials
  for update to authenticated using (public.can_manage_stock()) with check (public.can_manage_stock());
create policy materials_delete_stock_managers on public.materials
  for delete to authenticated using (public.can_manage_stock());

create policy stock_read_authenticated on public.stock_movements
  for select to authenticated using (public.can_manage_stock() or public.can_access_request(request_id));
create policy stock_insert_stock_managers on public.stock_movements
  for insert to authenticated
  with check (public.can_manage_stock() and responsible_id = (select auth.uid()));
-- Movimentações são imutáveis pelo cliente: correções devem ser lançadas como
-- nova movimentação, preservando o histórico.

