-- Gestão de Demandas DelRio | estrutura inicial com RLS restritiva
-- Execute uma única vez em um projeto Supabase NOVO, antes de liberar usuários.
-- Não use service_role no navegador. O perfil inicial de cada usuário será colaborador.

create extension if not exists pgcrypto;

create type public.app_role as enum ('admin','gestor','colaborador');
create type public.request_status as enum ('recebida','em_analise','aguardando_aprovacao','em_execucao','concluida','cancelada');
create type public.request_priority as enum ('baixa','media','alta','urgente');

create table public.areas (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default 'Usuário',
  email text,
  role public.app_role not null default 'colaborador',
  area_id uuid references public.areas(id),
  job_title text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.requests (
  id uuid primary key default gen_random_uuid(),
  protocol bigint generated by default as identity unique,
  title text not null,
  description text,
  area_id uuid not null references public.areas(id),
  requester_id uuid not null references public.profiles(id),
  owner_id uuid references public.profiles(id),
  priority public.request_priority not null default 'media',
  status public.request_status not null default 'recebida',
  due_date date not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz
);

create table public.request_assignees (
  request_id uuid not null references public.requests(id) on delete cascade,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  primary key (request_id, profile_id)
);

create table public.request_history (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.requests(id) on delete cascade,
  changed_by uuid references public.profiles(id),
  field_name text not null,
  old_value text,
  new_value text,
  note text,
  created_at timestamptz not null default now()
);

create table public.materials (
  id uuid primary key default gen_random_uuid(),
  sku text unique,
  name text not null,
  description text,
  unit text not null default 'un',
  quantity numeric(12,2) not null default 0 check (quantity >= 0),
  minimum_quantity numeric(12,2) not null default 0 check (minimum_quantity >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.stock_movements (
  id uuid primary key default gen_random_uuid(),
  material_id uuid not null references public.materials(id),
  request_id uuid references public.requests(id),
  movement_type text not null check (movement_type in ('entrada','saida','reserva','cancelamento_reserva')),
  quantity numeric(12,2) not null check (quantity > 0),
  responsible_id uuid references public.profiles(id),
  notes text,
  created_at timestamptz not null default now()
);

