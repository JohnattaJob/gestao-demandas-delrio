-- Cria automaticamente um perfil básico para cada novo usuário cadastrado no Auth.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, email, role)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'full_name', ''), nullif(new.raw_user_meta_data ->> 'name', ''), 'Usuário'),
    new.email,
    'colaborador'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Funções auxiliares SECURITY DEFINER evitam recursão nas políticas RLS.
create or replace function public.is_manager()
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid())
      and p.active = true
      and p.role in ('admin','gestor')
  );
$$;

create or replace function public.can_access_request(target_request uuid)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select public.is_manager() or exists (
    select 1
    from public.requests r
    left join public.request_assignees ra on ra.request_id = r.id
    where r.id = target_request
      and (
        r.requester_id = (select auth.uid())
        or r.owner_id = (select auth.uid())
        or ra.profile_id = (select auth.uid())
      )
  );
$$;

create or replace function public.can_manage_stock()
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select public.is_manager() or exists (
    select 1 from public.profiles p
    join public.areas a on a.id = p.area_id
    where p.id = (select auth.uid())
      and p.active = true
      and a.name = 'Materiais e Estoque'
  );
$$;

-- Colaborador atribuído pode atualizar o andamento, mas não prioridade, prazo,
-- área, solicitante ou responsável. Gestores/admins podem editar todos os campos.
create or replace function public.guard_request_updates()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_manager() then
    if new.title is distinct from old.title
      or new.description is distinct from old.description
      or new.area_id is distinct from old.area_id
      or new.requester_id is distinct from old.requester_id
      or new.owner_id is distinct from old.owner_id
      or new.priority is distinct from old.priority
      or new.due_date is distinct from old.due_date
      or new.created_at is distinct from old.created_at
      or new.protocol is distinct from old.protocol
      or new.completed_at is distinct from old.completed_at then
      raise exception 'Somente gestores podem alterar os dados administrativos da solicitação.';
    end if;
  end if;
  new.updated_at := now();
  if new.status = 'concluida' then
    new.completed_at := coalesce(old.completed_at, now());
  elsif new.status is distinct from old.status then
    new.completed_at := null;
  end if;
  return new;
end;
$$;

create trigger requests_guard_updates
  before update on public.requests
  for each row execute procedure public.guard_request_updates();

